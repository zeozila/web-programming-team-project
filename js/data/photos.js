// Wikimedia serves resized copies, so we ask for the size we actually need.
// Widths that Wikimedia pre-renders: 330, 500, 960, 1280, 1920.
export function photoUrl(key, width = 960) {
  const photo = PHOTOS[key];
  if (!photo) return "";
  const size = Math.min(width, photo.width >= 1920 ? 1920 : 1280);
  return photo.src.replace("/1280px-", `/${size}px-`);
}

export function getPhoto(key) {
  return PHOTOS[key];
}

export function allPhotos() {
  return Object.entries(PHOTOS).map(([key, photo]) => ({ key, ...photo }));
}
